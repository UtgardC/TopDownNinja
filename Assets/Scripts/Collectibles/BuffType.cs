// Tipos de buff temporal disponibles para el jugador.
// Cada valor corresponde a una estadística diferente que puede potenciarse.
public enum BuffType
{
    Speed,        // Aumenta la velocidad de movimiento
    Damage,       // Aumenta el daño del ataque principal
    AttackSpeed   // Aumenta la velocidad de ataque (reduce el cooldown)
}
